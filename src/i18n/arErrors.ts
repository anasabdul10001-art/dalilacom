/** The Arabic for an English-only error message (by its text, else by its code); null when there is nothing to change. */
export function arabicForError(code: string, message: string): string | null {
  if (typeof message !== "string" || !message || /[؀-ۿ]/.test(message)) return null;
  return MESSAGES[message.trim()] ?? BY_CODE[code] ?? null;
}
